// renderClamdConf derives clamd's configuration from the AV settings. clamd
// listens only on the configured Unix socket and loads every database in
// DatabaseDir, which includes the activated custom definitions.
func (m *AVManager) renderClamdConf(cfg config.AVConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by containd; edits are overwritten.\n")
	b.WriteString("Foreground yes\n")
	fmt.Fprintf(&b, "LocalSocket %s\n", clamdSocket(cfg))
	b.WriteString("LocalSocketMode 660\n")
	b.WriteString("FixStaleSocket yes\n")
	fmt.Fprintf(&b, "DatabaseDirectory %s\n", m.opts.DatabaseDir)
	b.WriteString("LogTime yes\n")
	limit := max(cfg.MaxSizeBytes, int64(100<<20))
	fmt.Fprintf(&b, "StreamMaxLength %d\nMaxScanSize %d\nMaxFileSize %d\nAlertExceedsMax yes\n", limit, limit, limit)
	if name, _, _, ok := m.daemonAccount(); ok {
		fmt.Fprintf(&b, "User %s\n", name)
	}
	return b.String()
}

func (m *AVManager) renderFreshclamConf() string {
	var b strings.Builder
	b.WriteString("# Generated by containd; edits are overwritten.\n")
	fmt.Fprintf(&b, "DatabaseDirectory %s\n", m.opts.DatabaseDir)
	owner := m.freshclamOwner()
	if owner != "" {
		fmt.Fprintf(&b, "DatabaseOwner %s\n", owner)
	}
	b.WriteString("DatabaseMirror database.clamav.net\n")
	b.WriteString("Foreground yes\n")
	return b.String()
}

// Validate checks the complete model and every variable text sink before
// filesystem or lifecycle operations. Clamd and FreshClam have no parse-only mode.
func (m *AVManager) Validate(_ context.Context, cfg config.AVConfig) error {
	if err := validateDaemonService(config.ServicesConfig{AV: cfg}); err != nil {
		return err
	}
	if err := validateDaemonPaths(m.opts.StateDir, m.opts.DatabaseDir); err != nil {
		return serviceConfigError(config.ServiceAV, err)
	}
	// User and DatabaseOwner are unquoted daemon tokens, even when the name
	// came from the host account database rather than the service model.
	name, _, _, _ := m.daemonAccount()
	for _, value := range []string{name, m.freshclamOwner()} {
		for _, c := range value {
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || strings.ContainsRune("_.-", c)) {
				return serviceConfigError(config.ServiceAV, fmt.Errorf("unsafe daemon account name"))
			}
		}
	}
	return nil
}

func (m *AVManager) freshclamOwner() string {
	owner, _, _, ok := m.daemonAccount()
	if !ok {
		if u, err := user.Current(); err == nil {
			return u.Username
		}
	}
	return owner
}
