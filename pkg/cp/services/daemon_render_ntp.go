package services

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/tonylturner/containd/pkg/cp/config"
)

func (m *NTPManager) renderChronyConfig(cfg config.NTPConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by containd — do not edit manually.\n")
	for _, s := range cfg.Servers {
		b.WriteString("server ")
		b.WriteString(s)
		b.WriteString(" iburst")
		if cfg.IntervalSeconds > 0 {
			// chrony uses log2 poll intervals; approximate from seconds.
			poll := intervalToPoll(cfg.IntervalSeconds)
			fmt.Fprintf(&b, " minpoll %d maxpoll %d", poll, poll)
		}
		b.WriteString("\n")
	}
	// Allow the clock to be stepped on first sync (important in containers).
	b.WriteString("\nmakestep 1 -1\n")
	// Drift file for clock rate tracking.
	b.WriteString("driftfile /data/chrony.drift\n")
	// Client-only mode (no NTP server).
	b.WriteString("port 0\ncmdport 0\n")
	return b.String()
}

func (m *NTPManager) Validate(ctx context.Context, cfg config.NTPConfig) error {
	if err := validateDaemonService(config.ServicesConfig{NTP: cfg}); err != nil {
		return err
	}
	if !cfg.Enabled {
		return nil
	}
	dir, err := os.MkdirTemp("", "containd-chrony-validate-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	return serviceConfigError(config.ServiceNTP, publishDaemonFiles(ctx, daemonFile{path: filepath.Join(dir, "chrony.conf"), body: []byte(m.renderChronyConfig(cfg)), check: m.validate}))
}

func (m *NTPManager) validate(ctx context.Context, configPath string) error {
	// chronyd -p parses and exits without starting a daemon or changing the clock.
	return checkDaemon(ctx, m.NTPDPath, "-p", "-f", configPath)
}
