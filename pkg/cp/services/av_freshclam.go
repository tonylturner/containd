const (
	defaultFreshclamInterval = 6 * time.Hour
	// freshclamRunTimeout bounds one FreshClam run so a stalled download
	// cannot hold the schedule forever.
	freshclamRunTimeout = 30 * time.Minute
	// FreshClam exit status 1 means the databases were already current.
	freshclamUpToDate = 1
)

// freshclamState is the single FreshClam schedule. Fields are guarded by
// AVManager.mu; the loop itself is started and stopped under AVManager.op.
type freshclamState struct {
	interval time.Duration
	cancel   context.CancelFunc
	done     chan struct{}
	now      chan struct{}
	running  bool
	last     time.Time
	err      string
}

// freshclamInterval parses updateSchedule, a Go duration such as "4h".
// Empty selects the six-hour default.
func freshclamInterval(s string) time.Duration {
	d, err := parseFreshclamSchedule(s)
	if err != nil {
		return defaultFreshclamInterval
	}
	return d
}

func parseFreshclamSchedule(s string) (time.Duration, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return defaultFreshclamInterval, nil
	}
	d, err := time.ParseDuration(s)
	if err != nil || d <= 0 {
		return 0, fmt.Errorf("%w: clamav.updateSchedule %q must be a positive duration such as 4h", ErrAVInvalid, s)
	}
	return d, nil
}

func (m *AVManager) freshclamConfPath() string {
	return filepath.Join(m.opts.StateDir, "freshclam.conf")
}

func (m *AVManager) renderFreshclamConf() string {
	var b strings.Builder
	b.WriteString("# Generated by containd; edits are overwritten.\n")
	fmt.Fprintf(&b, "DatabaseDirectory %s\n", m.opts.DatabaseDir)
	owner, _, _, ok := m.daemonAccount()
	if !ok {
		if u, err := user.Current(); err == nil {
			owner = u.Username
		}
	}
	if owner != "" {
		fmt.Fprintf(&b, "DatabaseOwner %s\n", owner)
	}
	b.WriteString("DatabaseMirror database.clamav.net\n")
	b.WriteString("Foreground yes\n")
	return b.String()
}

// ensureFreshclam runs the single FreshClam schedule when cfg enables it.
// An unchanged schedule keeps the running loop. Callers hold m.op.
func (m *AVManager) ensureFreshclam(cfg config.AVConfig) error {
	if !cfg.ClamAV.FreshclamEnabled {
		m.stopFreshclam()
		return nil
	}
	interval, err := parseFreshclamSchedule(cfg.ClamAV.UpdateSchedule)
	if err != nil {
		return err
	}
	m.mu.Lock()
	unchanged := m.fresh.done != nil && m.fresh.interval == interval
	m.mu.Unlock()
	if unchanged {
		return nil
	}
	m.stopFreshclam()
	if err := os.MkdirAll(m.opts.StateDir, 0o755); err != nil {
		return fmt.Errorf("prepare av state directory: %w", err)
	}
	if err := writeFileAtomic(m.freshclamConfPath(), []byte(m.renderFreshclamConf()), 0o644); err != nil {
		return fmt.Errorf("write freshclam config: %w", err)
	}
	ctx, cancel := context.WithCancel(m.ctx)
	done := make(chan struct{})
	now := make(chan struct{}, 1)
	m.mu.Lock()
	m.fresh.interval = interval
	m.fresh.cancel = cancel
	m.fresh.done = done
	m.fresh.now = now
	m.mu.Unlock()
	m.wg.Add(1)
	go func() {
		defer m.wg.Done()
		defer close(done)
		m.freshclamLoop(ctx, interval, now)
	}()
	return nil
}

// stopFreshclam ends the schedule, including a running download, and waits
// for the loop to exit. Callers hold m.op.
func (m *AVManager) stopFreshclam() {
	m.mu.Lock()
	cancel, done := m.fresh.cancel, m.fresh.done
	m.fresh.cancel, m.fresh.done, m.fresh.now = nil, nil, nil
	m.mu.Unlock()
	if cancel == nil {
		return
	}
	cancel()
	<-done
}

func (m *AVManager) freshclamLoop(ctx context.Context, interval time.Duration, now <-chan struct{}) {
	m.runFreshclam(ctx)
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		case <-now:
		}
		m.runFreshclam(ctx)
	}
}

// RunFreshclamNow asks the schedule for an immediate update. It returns once
// the request is queued; Status reports the run and its result.
func (m *AVManager) RunFreshclamNow() error {
	if m == nil {
		return ErrAVStopped
	}
	m.mu.Lock()
	defer m.mu.Unlock()
	cfg := m.lastCfg
	switch {
	case !cfg.Enabled || avMode(cfg) != "clamav":
		return fmt.Errorf("%w: definition updates require AV enabled in clamav mode", ErrAVConflict)
	case !cfg.ClamAV.FreshclamEnabled:
		return fmt.Errorf("%w: freshclam is disabled", ErrAVConflict)
	case m.fresh.now == nil:
		return fmt.Errorf("%w: freshclam schedule is not running", ErrAVConflict)
	case m.fresh.running:
		return fmt.Errorf("%w: freshclam already running", ErrAVConflict)
	}
	select {
	case m.fresh.now <- struct{}{}:
		return nil
	default:
		return fmt.Errorf("%w: freshclam update already requested", ErrAVConflict)
	}
}

func (m *AVManager) runFreshclam(ctx context.Context) {
	m.mu.Lock()
	m.fresh.running = true
	m.mu.Unlock()
	updated, err := m.execFreshclam(ctx)
	m.mu.Lock()
	m.fresh.running = false
	if err != nil {
		m.fresh.err = err.Error()
	} else {
		m.fresh.err = ""
		m.fresh.last = time.Now().UTC()
	}
	m.mu.Unlock()
	if err != nil {
		if ctx.Err() == nil {
			m.emit("service.av.freshclam_failed", map[string]any{"error": err.Error()})
		}
		return
	}
	m.emit("service.av.freshclam_ok", map[string]any{"updated": updated})
	m.afterDefinitionsUpdate(ctx, updated)
}

// execFreshclam runs one FreshClam update and reports whether it changed the
// databases.
func (m *AVManager) execFreshclam(ctx context.Context) (bool, error) {
	ctx, cancel := context.WithTimeout(ctx, freshclamRunTimeout)
	defer cancel()
	// nosemgrep: go.lang.security.audit.dangerous-exec-command.dangerous-exec-command
	cmd := exec.CommandContext(ctx, m.opts.FreshclamPath, "--config-file="+m.freshclamConfPath(), "--stdout")
	cmd.Env = m.freshclamEnv()
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	cmd.Cancel = func() error { return cmd.Process.Signal(syscall.SIGTERM) }
	cmd.WaitDelay = 5 * time.Second
	err := cmd.Run()
	var exitErr *exec.ExitError
	switch {
	case err == nil:
		return true, nil
	case errors.As(err, &exitErr) && exitErr.ExitCode() == freshclamUpToDate:
		return false, nil
	case ctx.Err() != nil:
		return false, fmt.Errorf("freshclam: %w", ctx.Err())
	default:
		return false, fmt.Errorf("freshclam: %s", exitText(err))
	}
}

// freshclamEnv is the child environment; it is never applied process-wide.
func (m *AVManager) freshclamEnv() []string {
	return os.Environ()
}

// afterDefinitionsUpdate reloads clamd after new databases arrived, or
// starts it when it had exited for lack of a database.
func (m *AVManager) afterDefinitionsUpdate(ctx context.Context, changed bool) {
	if err := m.lock(ctx); err != nil {
		return
	}
	defer m.unlock()
	cfg := m.Current()
	if !cfg.Enabled || avMode(cfg) != "clamav" {
		return
	}
	m.mu.Lock()
	running := m.clamd.running()
	m.mu.Unlock()
	if running {
		if !changed {
			return
		}
		if err := m.reloadClamd(ctx, cfg); err != nil {
			m.emit("service.av.clamav_reload_failed", map[string]any{"error": err.Error()})
			return
		}
	} else if err := m.ensureClamd(cfg); err != nil {
		m.emit("service.av.clamav_start_failed", map[string]any{"error": err.Error()})
		return
	}
	m.mu.Lock()
	m.defsGen++
	m.mu.Unlock()
}
